# revenge_checks.py
# File 21. Two things are checked.
#
# (A) A general fact about the revision operator A(X) = U \ Ref(X) when Ref is
#     monotone and U is finite: the sequence from U has period at most 2, so
#     every content is stably in, stably out, or oscillates with period 2.
#     No content is ever both stably in and stably out. We verify this by
#     brute force over ALL monotone Ref on a small U, not just the toy rules.
#
# (B) The revenge sentences. Priest's objection to revision theories is that
#     the stability predicate itself generates a strengthened liar. Inside
#     the model, a content's refutation condition can only depend on the
#     current commitment set X, not on the whole sequence. So any self-
#     referential rule we can write is of the form "r refuted iff f(X)".
#     We enumerate every such rule for a single self-referential content r
#     added to a fixed background and classify r. The result shows what the
#     model can and cannot say about its own stability predicate.
import itertools, json

# ---------- (A) ----------
def all_monotone_refs(U):
    # Ref: subsets of U -> subsets of U, monotone. Enumerate by choosing, for
    # each content c, an upward-closed family of X in which c is refuted.
    subsets = [frozenset(s) for r in range(len(U) + 1) for s in itertools.combinations(U, r)]
    # upward-closed families generated by antichains; brute-force all families
    # of subsets and keep the upward-closed ones (U small, so feasible).
    fams = []
    for bits in range(1 << len(subsets)):
        fam = {subsets[i] for i in range(len(subsets)) if bits >> i & 1}
        ok = all((T in fam) for S in fam for T in subsets if S <= T)
        if ok:
            fams.append(fam)
    for choice in itertools.product(fams, repeat=len(U)):
        def Ref(X, choice=choice):
            X = frozenset(X)
            return {U[i] for i in range(len(U)) if X in choice[i]}
        yield Ref

def period(U, Ref, steps=16):
    X = set(U); seq = [frozenset(X)]
    for _ in range(steps):
        X = set(U) - Ref(X); seq.append(frozenset(X))
    tail = seq[-6:]
    p1 = all(t == tail[0] for t in tail)
    p2 = all(tail[i] == tail[i % 2] for i in range(len(tail)))
    return 1 if p1 else (2 if p2 else None)

U3 = ["a", "b", "c"]
periods = {}
both = 0
count = 0
for Ref in all_monotone_refs(U3):
    count += 1
    p = period(U3, Ref)
    periods[p] = periods.get(p, 0) + 1
    # check "both stably in and stably out" is impossible: trivially so, but
    # verify the even and odd limits are comparable (odd ⊆ even)
    X = set(U3); seq = [frozenset(X)]
    for _ in range(12):
        X = set(U3) - Ref(X); seq.append(frozenset(X))
    even, odd = seq[-2], seq[-1]
    if not (odd <= even or even <= odd):
        both += 1

# ---------- (B) ----------
# Background: the stable core of the toy model (file 17) plus one new content r.
background_in = ["D", "E", "G", "P"]      # never refuted
background_out = ["S", "W", "Z"]          # refuted whenever D / M / P present (here: always)
U = background_in + background_out + ["r"]

def make_ref(rule):
    # rule: function from (r in X) -> bool, the only self-referential dependence available
    def Ref(X):
        out = set(background_out)
        if rule("r" in X):
            out.add("r")
        return out
    return Ref

rules = {
    "r refuted iff r in X   (liar / 'no ultimate truth')": lambda rin: rin,
    "r refuted iff r not in X (truth-teller mirror)": lambda rin: not rin,
    "r never refuted         (harmless self-inclusion, 'all is empty')": lambda rin: False,
    "r always refuted        (svabhava claim)": lambda rin: True,
}
results = {}
for name, rule in rules.items():
    Ref = make_ref(rule)
    X = set(U); seq = [frozenset(X)]
    for _ in range(10):
        X = set(U) - Ref(X); seq.append(frozenset(X))
    tail = ["r" in s for s in seq[-6:]]
    cls = "stably in" if all(tail) else ("stably out" if not any(tail) else "unstable")
    results[name] = {"class": cls, "tail": tail}

report = {
    "A: monotone Ref functions enumerated on 3 contents": count,
    "A: periods found": {str(k): v for k, v in periods.items()},
    "A: cases where odd and even limits are incomparable": both,
    "B: every expressible self-referential rule, classified": results,
    "B: note": "the predicate 'stably in' depends on the whole sequence, not on X; "
               "no Ref rule can express it, so the strengthened liar is not a content of the model",
}
print(json.dumps(report, ensure_ascii=False, indent=1))
